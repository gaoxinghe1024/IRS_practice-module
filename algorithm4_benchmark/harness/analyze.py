def summarize(scored: list[dict]) -> list[dict]:
    out = []
    combos = sorted({(r["model_label"], r["group"]) for r in scored})
    for ml, grp in combos:
        sub = [r for r in scored if r["model_label"] == ml and r["group"] == grp]
        row = {"model_label": ml, "group": grp, "n": len(sub)}
        for k in METRICS:
            vals = [fnum(r.get(k)) for r in sub]
            vals = [v for v in vals if v is not None]
            row[k] = mean(vals)
        out.append(row)
    return out


def rag_lift(scored: list[dict], n_boot: int, seed: int) -> list[dict]:
    rng = random.Random(seed)
    by_mq: dict[tuple, dict] = defaultdict(dict)
    for r in scored:
        if r["group"] in ("R", "N"):
            by_mq[(r["model_label"], r["qid"])][r["group"]] = r
    out = []
    for ml in MODELS:
        row = {"model_label": ml}
        for k in METRICS:
            diffs = []
            for (m, _q), gs in by_mq.items():
                if m != ml or "R" not in gs or "N" not in gs:
                    continue
                a, b = fnum(gs["R"].get(k)), fnum(gs["N"].get(k))
                if a is not None and b is not None:
                    diffs.append(a - b)
            row[k] = mean(diffs)
            row[k + "_n_pairs"] = len(diffs)
            if diffs and n_boot > 0:
                lo, hi = boot_ci(diffs, n_boot, rng)
                row[k + "_lo"], row[k + "_hi"] = lo, hi
        out.append(row)
    return out


def token_usage(raw: list[dict]) -> list[dict]:
    out = []
    for ml in MODELS:
        row = {"model_label": ml}
        for grp in ("R", "N"):
            sub = [r for r in raw if r.get("model_label") == ml and r.get("group") == grp
                   and r.get("status") == "ok"]
            for field in ("input_tokens", "output_tokens", "completion_thinking_tokens"):
                vals = [fnum(r.get(field)) for r in sub]
                vals = [v for v in vals if v is not None]
                row[f"{grp}_{field}"] = mean(vals)
        out.append(row)
    return out


def latency(raw: list[dict]) -> list[dict]:
    out = []
    for ml in MODELS:
        sub = [r for r in raw if r.get("model_label") == ml and r.get("group") == "R"
               and r.get("status") == "ok"]
        durs = [fnum(r.get("duration_ms")) for r in sub]
        durs = [d for d in durs if d is not None]
        lin, near = p95(durs)
        out.append({"model_label": ml, "n": len(durs),
                    "p95_linear_s": lin, "p95_nearest_rank_s": near,
                    "over_20s": sum(1 for d in durs if d > 20000),
                    "over_20s_share": (sum(1 for d in durs if d > 20000) / len(durs))
                    if durs else None})
    return out


# ---------- tables 1-2 and derived CSVs (generated from results/scored.csv) ----------

TABLE_N_BOOT = 10000        # published CIs always use 10,000 resamples (seed 42)
T_MODEL_LABEL = "T(system)"  # model_label of the template rows in scored.csv
T_DISPLAY = "T (system default)"
GROUP_DISPLAY = {"R": "R (RAG)", "N": "N (LLM only)", "T": "T (template)"}
OFFTOPIC_QID = "T10"         # offtopic trap: excluded from the frank-rate metric

# (key, display header, question type or None = all 80 questions, scored.csv column)
TABLE1_SPECS = [
    ("scene_top1", "Scene Top1", "scene", "top1"),
    ("episode_ok", "Episode OK", "scene", "episode_ok"),
    ("all_satisfy", "All Satisfy", "constraint", "all_satisfy"),
    ("inkb_rate", "In-KB Rate", None, "in_kb_reply_ok"),
    ("judge_avg", "Judge Avg (3-judge excl. same vendor)", None, "judge_avg"),
    ("judge_all_avg", "Judge Avg (all judges)", None, "judge_all_avg"),
]
# question type -> [(metric key, display name, scored.csv column; None = per-work rate)]
TABLE2_SPECS = [
    ("scene", [("top1", "Top1", "top1"), ("episode_ok", "Episode OK", "episode_ok")]),
    ("constraint", [("all_satisfy", "All Satisfy", "all_satisfy"),
                    ("per_work_rate", "Per-Work Rate", None)]),
    ("similar", [("inkb_rate", "In-KB Rate", "in_kb_reply_ok")]),
    ("mood", [("mood_ok", "Mood OK", "mood_ok")]),
    ("fact", [("fact_ok", "Fact OK", "fact_ok")]),
    ("trap", [("rule_frank", "Rule Frank", "rule_frank")]),
]
OUT_OF_KB_COLS = ["qid", "type", "model", "group", "n_out_kb", "n_echo",
                  "n_kb_variant", "n_out_kb_final", "echo_names", "kbvar_names",
                  "kept_names", "in_kb_reply_ok"]


def metric_values(rows: list[dict], qtype: str | None, col: str | None) -> list[float]:
    """One value per question. col None = per-work constraint rate: recommended
    in-KB works satisfying the constraints / all recommended titles (0 if none)."""
    out = []
    for r in rows:
        if qtype and r["type"] != qtype:
            continue
        if col == "rule_frank" and r["qid"] == OFFTOPIC_QID:
            continue
        if col is None:
            n_rec = fnum(r.get("n_rec"))
            if n_rec is not None:
                out.append(fnum(r["n_rec_satisfy"]) / n_rec if n_rec > 0 else 0.0)
            continue
        v = fnum(r.get(col))
        if v is not None:
            out.append(v)
    return out


def cell_stats(vals: list[float]):
    """(mean, ci_lo, ci_hi): percentile bootstrap over questions, one fresh
    random.Random(42) per cell so a cell never depends on its neighbours."""
    if not vals:
        return (None, None, None)
    lo, hi = boot_ci(vals, TABLE_N_BOOT, random.Random(SEED))
    return (mean(vals), lo, hi)


def table1_rows(scored: list[dict]) -> list[dict]:
    cells = [(T_DISPLAY, "T", [r for r in scored if r["group"] == "T"])]
    for ml in MODELS:
        for grp in ("R", "N"):
            cells.append((ml, grp, [r for r in scored
                                    if r["model_label"] == ml and r["group"] == grp]))
    rows = []
    for model, grp, sub in cells:
        row = {"model": model, "group": grp}
        for key, _hdr, qtype, col in TABLE1_SPECS:
            m, lo, hi = cell_stats(metric_values(sub, qtype, col))
            row[f"{key}_mean"], row[f"{key}_ci_lo"], row[f"{key}_ci_hi"] = m, lo, hi
        rows.append(row)
    return rows


def table2_rows(scored: list[dict]) -> list[dict]:
    rows = []
    for ml in MODELS:
        for grp in ("R", "N"):
            sub = [r for r in scored if r["model_label"] == ml and r["group"] == grp]
            for qtype, metrics in TABLE2_SPECS:
                for key, _name, col in metrics:
                    vals = metric_values(sub, qtype, col)
                    m, lo, hi = cell_stats(vals)
                    rows.append({"model": ml, "group": grp, "qtype": qtype,
                                 "n": len(vals), "metric": key,
                                 "mean": m, "ci_lo": lo, "ci_hi": hi})
    return rows


def table1_columns() -> list[str]:
    cols = ["model", "group"]
    for key, *_ in TABLE1_SPECS:
        cols += [f"{key}_mean", f"{key}_ci_lo", f"{key}_ci_hi"]
    return cols


TABLE2_COLUMNS = ["model", "group", "qtype", "n", "metric", "mean", "ci_lo", "ci_hi"]


def _fmt(m, lo, hi) -> str:
    return f"{m:.3f} [{lo:.3f}, {hi:.3f}]"


def table1_markdown(rows: list[dict], scored: list[dict]) -> str:
    head = ["Model", "Group"] + [h for _k, h, *_ in TABLE1_SPECS]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for r in rows:
        cells = [r["model"], GROUP_DISPLAY[r["group"]]]
        cells += [_fmt(r[f"{k}_mean"], r[f"{k}_ci_lo"], r[f"{k}_ci_hi"])
                  for k, *_ in TABLE1_SPECS]
        lines.append("| " + " | ".join(cells) + " |")
    first = [r for r in scored if r["group"] == "T"]
    ns = ", ".join(f"{h} {len(metric_values(first, q, c))}"
                   for _k, h, q, c in TABLE1_SPECS)
    lines += ["", f"Cell = mean [95% CI]; n questions per cell: {ns}. "
                  f"CI: percentile bootstrap over questions, {TABLE_N_BOOT:,} "
                  f"resamples, random.Random({SEED}) per cell."]
    return "\r\n".join(lines) + "\r\n"


def table2_markdown(rows: list[dict]) -> str:
    names = {(q, k): n for q, ms in TABLE2_SPECS for k, n, _c in ms}
    head = ["Model", "Group", "QType", "Metric", "n", "Mean [95% CI]"]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for r in rows:
        cells = [r["model"], GROUP_DISPLAY[r["group"]], r["qtype"],
                 names[(r["qtype"], r["metric"])], str(r["n"]),
                 _fmt(r["mean"], r["ci_lo"], r["ci_hi"])]
        lines.append("| " + " | ".join(cells) + " |")
    lines += ["", f"CI: percentile bootstrap over questions, {TABLE_N_BOOT:,} "
                  f"resamples, random.Random({SEED}) per cell. Per-Work Rate = "
                  "mean over constraint questions of (recommended in-KB works "
                  "satisfying the constraints / all recommended titles; 0 if none). "
                  f"Rule Frank excludes {OFFTOPIC_QID} (n = 11)."]
    return "\r\n".join(lines) + "\r\n"


def inkb_rate_rows(scored: list[dict]) -> list[dict]:
    """Reply-level in-KB citation rate per model (N, R) and the paired lift."""
    k: dict[str, dict[str, list[int]]] = defaultdict(
        lambda: {"N": [0, 0], "R": [0, 0]})
    for r in scored:
        v = fnum(r.get("in_kb_reply_ok"))
        if r["group"] in ("N", "R") and v is not None:
            k[r["model_label"]][r["group"]][0] += int(v)
            k[r["model_label"]][r["group"]][1] += 1
    out = []
    for ml in sorted(k):
        n = k[ml]["N"][0] / k[ml]["N"][1]
        rr = k[ml]["R"][0] / k[ml]["R"][1]
        out.append({"model": ml, "N_inkb_reply": f"{n:.4f}",
                    "R_inkb_reply": f"{rr:.4f}", "R-N": f"{rr - n:.4f}"})
    return out


def out_of_kb_rows(scored: list[dict], raw_recs: list[dict], scorer, testset: dict,
                   aliases: dict) -> list[dict]:
    """Per-reply out-of-KB titles with echo / in-KB-variant removal (final caliber).

    Title strings are re-extracted from the saved replies (scored.csv joins them
    with ';', which some titles contain); counts and in_kb_reply_ok are checked
    against scored.csv.
    """
    rows = []
    for src, r in zip(raw_recs, scored):
        if (src["qid"], src["model_label"], src["group"]) != \
                (r["qid"], r["model_label"], r["group"]):
            raise ValueError("raw.jsonl.gz and scored.csv rows are not aligned")
        names = scorer.mentioned_animes(src.get("reply") or "", aliases)["out_of_kb"]
        qt = scorer.query_titles(r["qid"], testset[r["qid"]], aliases)
        echo, kbvar, kept = [], [], []
        for s in names:
            if scorer.is_echo(s, qt):
                echo.append(s)
            elif scorer.is_kb_variant(s, aliases):
                kbvar.append(s)
            else:
                kept.append(s)
        ok = (not kept) and (int(r["n_kb_hits"]) + len(names)) > 0
        if len(names) != int(r["n_out_kb"]) or str(ok) != r["in_kb_reply_ok"]:
            raise ValueError(f"scored.csv disagrees with the replies at "
                             f"{r['qid']} / {r['model_label']} / {r['group']}")
        rows.append({"qid": r["qid"], "type": r["type"], "model": r["model_label"],
                     "group": r["group"], "n_out_kb": len(names),
                     "n_echo": len(echo), "n_kb_variant": len(kbvar),
                     "n_out_kb_final": len(kept), "echo_names": ";".join(echo),
                     "kbvar_names": ";".join(kbvar), "kept_names": ";".join(kept),
                     "in_kb_reply_ok": r["in_kb_reply_ok"]})
    return rows


def write_dict_csv(path: Path, rows: list[dict], cols: list[str]) -> None:
    with open(path, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        w.writerows(rows)


def write_tables(results: Path) -> list[Path]:
    """Generate tables 1-2 (results/tables/) and the two derived CSVs
    (results/extra/) from results/scored.csv."""
    try:
        from harness import score as scorer  # module execution
    except ImportError:  # script execution
        import score as scorer  # type: ignore
    scored = read_csv(results / "scored.csv")
    testset = {q["id"]: q for q in load_jsonl(PKG / "data" / "testset_v1.jsonl")}
    aliases = scorer.load_aliases(PKG / "data" / "aliases.json")
    raw_recs = load_jsonl(results / "raw.jsonl.gz")
    t1, t2 = table1_rows(scored), table2_rows(scored)
    tdir, xdir = results / "tables", results / "extra"
    tdir.mkdir(parents=True, exist_ok=True)
    xdir.mkdir(parents=True, exist_ok=True)
    outs = [tdir / "table1_main_results.csv", tdir / "table1_main_results.md",
            tdir / "table2_by_type.csv", tdir / "table2_by_type.md",
            xdir / "inkb_reply_rate_per_reply.csv", xdir / "out_of_kb_per_reply.csv"]
    write_dict_csv(outs[0], t1, table1_columns())
    with open(outs[1], "w", newline="", encoding="utf-8") as f:
        f.write(table1_markdown(t1, scored))
    write_dict_csv(outs[2], t2, TABLE2_COLUMNS)
    with open(outs[3], "w", newline="", encoding="utf-8") as f:
        f.write(table2_markdown(t2))
    write_dict_csv(outs[4], inkb_rate_rows(scored),
                   ["model", "N_inkb_reply", "R_inkb_reply", "R-N"])
    write_dict_csv(outs[5], out_of_kb_rows(scored, raw_recs, scorer, testset, aliases),
                   OUT_OF_KB_COLS)
    return outs


def write_scored_csv(path: Path, rows: list[dict]) -> None:
    """Write results/scored.csv (fixed column order; unset cells stay empty)."""
    with open(path, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=SCORED_COLS, restval="",
                           extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)


def write_csv(path: Path, rows: list[dict]) -> None:
    keys: list[str] = []
    for r in rows:
        for k in r:
            if k not in keys:
                keys.append(k)
    with open(path, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=keys, restval="")
        w.writeheader()
        w.writerows(rows)


def main() -> int:
    ap = argparse.ArgumentParser(
        description="Replay analysis over saved evaluation outputs (offline).")
    ap.add_argument("--results-dir", default="results")
    ap.add_argument("--out-dir", default=None,
                    help="output directory (default: <results-dir>/replay)")
    ap.add_argument("--bootstrap", type=int, default=10000,
                    help="bootstrap resamples for CI columns (0 = skip CIs)")
    ap.add_argument("--fast", action="store_true",
                    help="quick mode: 200 resamples (tests)")
    ap.add_argument("--rescore", action="store_true",
                    help="recompute rule metrics from raw replies via harness/score.py")
    ap.add_argument("--write-scored", action="store_true",
                    help="with --rescore: rewrite results/scored.csv from the "
                         "re-scored replies and re-aggregated judge outputs")
    ap.add_argument("--tables", action="store_true",
                    help="generate tables 1-2 and the two derived CSVs from "
                         "results/scored.csv, then exit")
    ap.add_argument("--pairwise-matrix", action="store_true",
                    help="regenerate results/extra/pairwise_centered_matrix.csv "
                         "from the saved judge outputs")
    ap.add_argument("--figures", action="store_true",
                    help="re-render results/figures/ (fig1-fig4, PNG + SVG) via "
                         "tools/make_figures.py (requires matplotlib), then exit")
    args = ap.parse_args()

    results = Path(args.results_dir)
    if not results.is_absolute():
        results = PKG / args.results_dir
    out_dir = Path(args.out_dir) if args.out_dir else results / "replay"
    if not out_dir.is_absolute():
        out_dir = PKG / out_dir

    n_boot = 200 if args.fast else args.bootstrap
    if args.write_scored and not args.rescore:
        ap.error("--write-scored requires --rescore")

    if args.pairwise_matrix:
        rows = pairwise_centered_matrix(results, n_boot, SEED)
        (results / "extra").mkdir(parents=True, exist_ok=True)
        with open(results / "extra" / "pairwise_centered_matrix.csv", "w",
                  newline="", encoding="utf-8-sig") as f:
            csv.writer(f).writerows(rows)
        print(f"pairwise matrix -> {results / 'extra' / 'pairwise_centered_matrix.csv'}")

    if args.rescore:
        try:
            from harness import score as scorer  # module execution
        except ImportError:  # script execution: python harness/analyze.py
            import score as scorer  # type: ignore
        testset = {q["id"]: q for q in load_jsonl(PKG / "data" / "testset_v1.jsonl")}
        aliases = scorer.load_aliases(PKG / "data" / "aliases.json")
        anime = scorer.load_anime(PKG / "data" / "kb" / "anime.db")
        retrieval = {x["id"]: x["retrieval"]
                     for x in load_jsonl(results / "retrieval.jsonl")}
        raw_recs = load_jsonl(results / "raw.jsonl.gz")
        scored = scorer.score_records(raw_recs, testset, aliases, anime, retrieval)
        # judge columns: re-aggregate from the saved judge outputs (same as the
        # packaged scored.csv; same-vendor exclusion inside harness/judge.py)
        try:
            from harness import judge as judger  # module execution
        except ImportError:  # script execution
            import judge as judger  # type: ignore
        jmap = {r["call_id"]: r for r in judger.aggregate(results)}
        for src, row in zip(raw_recs, scored):
            j = jmap.get(src.get("call_id"))
            if j:
                for c in JUDGE_COLS:
                    row[c] = j.get(c)
        if args.write_scored:
            write_scored_csv(results / "scored.csv", scored)
            print(f"scored.csv -> {results / 'scored.csv'}")
    else:
        scored = read_csv(results / "scored.csv")

    if args.tables:
        for p in write_tables(results):
            print(f"table -> {p}")
        print("TABLES_OK")
        return 0

    if args.figures:
        import importlib.util
        spec = importlib.util.spec_from_file_location(
            "make_figures", PKG / "tools" / "make_figures.py")
        make_figures = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(make_figures)
        for p in make_figures.render_all(results, results / "figures"):
            print(f"figure -> {p}")
        print("FIGURES_OK")
        return 0

    raw = load_jsonl(results / "raw.jsonl.gz")

    out_dir.mkdir(parents=True, exist_ok=True)
    write_csv(out_dir / "replay_summary.csv", summarize(scored))
    write_csv(out_dir / "replay_rag_lift.csv", rag_lift(scored, n_boot, SEED))
    write_csv(out_dir / "replay_token_usage.csv", token_usage(raw))
    write_csv(out_dir / "replay_latency.csv", latency(raw))

    print(f"replay outputs -> {out_dir}")
    print("ANALYZE_OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
