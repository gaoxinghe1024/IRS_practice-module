def load_jsonl(path: Path) -> list[dict]:
    op = gzip.open if str(path).endswith(".gz") else open
    with op(path, "rt", encoding="utf-8") as f:
        return [json.loads(l) for l in f if l.strip()]


def read_csv(path: Path) -> list[dict]:
    with open(path, encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def fnum(x):
    if isinstance(x, bool):
        return 1.0 if x else 0.0
    if isinstance(x, str):
        if x.strip() in ("True", "true"):
            return 1.0
        if x.strip() in ("False", "false"):
            return 0.0
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def mean(vals: list[float]):
    return sum(vals) / len(vals) if vals else None


def boot_ci(diffs: list[float], n_boot: int, rng: random.Random):
    if not diffs or len(set(diffs)) == 1:
        m = mean(diffs)
        return (m, m)
    n = len(diffs)
    means = sorted(
        sum(diffs[rng.randrange(n)] for _ in range(n)) / n for _ in range(n_boot))
    return (means[int(0.025 * n_boot)], means[int(0.975 * n_boot) - 1])


def p95(durs_ms: list[float]) -> tuple[float, float]:
    """(linear interpolation, nearest-rank) p95 in seconds."""
    s = sorted(durs_ms)
    if not s:
        return (None, None)
    if len(s) == 1:
        return (s[0] / 1000.0, s[0] / 1000.0)
    h = 0.95 * (len(s) - 1)
    lo, hi = int(h), min(int(h) + 1, len(s) - 1)
    linear = (s[lo] + (h - lo) * (s[hi] - s[lo])) / 1000.0
    nearest = s[max(0, int(0.95 * len(s)) - 1)] / 1000.0
    return (linear, nearest)


# ---------- centered judge scores + pairwise matrix (same caliber as the main table) ----------

def centered_scores(results: Path) -> dict[str, dict[str, float]]:
    """Per-question centered R-group judge scores.

    Same caliber as the main table (results/extra/judge_scores_centered.csv,
    column R_adj, generated by harness/judge.py): each judge's global mean
    (over all 80 questions and all scored candidates) is subtracted, then the
    per-question score averages the eligible judges — excluding judges of the
    same vendor as the model (JVENDOR/MVENDOR in harness/judge.py).
    """
    try:
        from harness.judge import JVENDOR, MVENDOR, DIMS  # module execution
    except ImportError:  # script execution: python harness/analyze.py
        from judge import JVENDOR, MVENDOR, DIMS  # type: ignore

    judge_scores = {}
    for r in load_jsonl(results / "judge_raw.jsonl.gz"):
        if r.get("status") in ("ok", "partial"):
            judge_scores[(r["judge"], r["qid"])] = r["scores"]
    label_of = {}
    for d in load_jsonl(results / "extra" / "judge_label_maps.jsonl.gz"):
        for e in d["labels"]:
            label_of[(d["judge"], d["qid"], e["model_label"], e["group"])] = e["label"]
    qids = sorted({q for (_, q) in judge_scores})
    judges = sorted({j for (j, _) in judge_scores})
    gmean = {j: mean([sum(sc[d] for d in DIMS) / 4
                      for (jj, _q), sc in judge_scores.items() if jj == j
                      for sc in sc.values()]) for j in judges}
    cent: dict[str, dict[str, float]] = {}
    for m in MODELS:
        panel = [j for j in judges if JVENDOR.get(j) != MVENDOR.get(m)]
        cent[m] = {}
        for q in qids:
            per_j = []
            for j in panel:
                sc = judge_scores.get((j, q))
                lab = label_of.get((j, q, m, "R"))
                if sc is None or lab is None or lab not in sc:
                    continue
                per_j.append(sum(sc[lab][d] for d in DIMS) / 4 - gmean[j])
            cent[m][q] = mean(per_j)
        assert all(v is not None for v in cent[m].values()), m
    return cent


def pairwise_centered_matrix(results: Path, n_boot: int, seed: int) -> list[list]:
    """15-pair matrix over centered judge scores; A−B = mean(A) − mean(B) per question.

    Written to results/extra/pairwise_centered_matrix.csv by --pairwise-matrix.
    """
    cent = centered_scores(results)
    qids = sorted(next(iter(cent.values())).keys())
    rows = [["model_a", "model_b", "mean_diff", "ci_lo", "ci_hi", "significant"]]
    for a, b in itertools.combinations(MODELS, 2):
        diffs = [cent[a][q] - cent[b][q] for q in qids]
        m = mean(diffs)
        lo, hi = boot_ci(diffs, n_boot, random.Random(seed))
        rows.append([a, b, round(m, 3), round(lo, 3), round(hi, 3),
                     "yes" if (lo > 0 or hi < 0) else "no"])
    return rows


