"""analyze.py — replay analysis: recompute every table from saved outputs.

Default (replay) mode reads only packaged files:
    results/scored.csv          per-reply metrics (rule + judge)
    results/raw.jsonl.gz        token usage + latency per call
and writes:
    replay_summary.csv          per model x group deterministic means
    replay_rag_lift.csv         paired R-N diffs + bootstrap CIs (seed 42)
    replay_token_usage.csv      per model input/output/reasoning means
    replay_latency.csv          p50/p95 (two methods) + over-20 s counts

With --rescore, per-reply rule metrics are recomputed from raw replies via
harness/score.py instead of being read from scored.csv; adding --write-scored
rewrites results/scored.csv from that path (rule columns from harness/score.py,
judge columns re-aggregated from results/judge_raw.jsonl.gz).

With --tables, results/tables/table1_main_results.* and table2_by_type.* and the
derived CSVs results/extra/inkb_reply_rate_per_reply.csv and
results/extra/out_of_kb_per_reply.csv are generated from results/scored.csv
(CIs: percentile bootstrap over questions, 10,000 resamples, random.Random(42)
per cell; independent of --bootstrap / --fast). The step ends the run.

Bootstrap resamples default to 10,000 (seed 42); pass --bootstrap 200 (or
--fast) for quick deterministic-only runs in tests. Deterministic columns are
bit-comparable across runs; only CI columns depend on the resample count.

With --figures, results/figures/ (fig1-fig4, PNG + SVG) is re-rendered from the
packaged tables and results/scored.csv by tools/make_figures.py (requires
matplotlib). The step ends the run.

No network, no model calls; the only third-party package is matplotlib, used by
--figures alone.
"""
