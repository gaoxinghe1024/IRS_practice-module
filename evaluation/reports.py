"""Collect the latest run of each experiment into docs/evaluation-results-<mode>.md."""

from __future__ import annotations

import json

from app.core.config import PROJECT_ROOT, Settings
from evaluation.runner import ORDER


def _attempt(d, mode: str) -> tuple[str, bool] | None:
    """(experiment, is_smoke) for a run directory named <date>-<time>-<mode>-<experiment>[-<tag>]-<hex4>."""
    parts = d.name.split("-")
    if len(parts) < 5 or parts[2] != mode:
        return None
    middle = parts[3:-1]
    for name in sorted(ORDER, key=len, reverse=True):
        if "-".join(middle) == name or "-".join(middle).startswith(name + "-"):
            return name, "-".join(middle).endswith("-smoke")
    return None


def latest_runs(settings: Settings) -> dict[str, dict]:
    """Latest finished, non-smoke run per experiment; a newer attempt without a manifest is flagged."""
    root = settings.evaluation_runs_dir
    found: dict[str, dict] = {}
    if not root.exists():
        return found
    for d in sorted(root.iterdir()):                       # names start with a timestamp: latest wins
        att = _attempt(d, settings.mode) if d.is_dir() else None
        if att is None or att[1]:
            continue
        m = d / "manifest.json"
        if not m.exists():
            if att[0] in found:
                found[att[0]]["newer_unfinished"] = d.name
            else:
                found[att[0]] = {"dir": None, "manifest": None, "newer_unfinished": d.name}
            continue
        man = json.loads(m.read_text())
        if man.get("dataset_mode") != settings.mode or man.get("smoke"):
            continue
        found[man["experiment"]] = {"dir": d, "manifest": man}
    return found


def _algorithm2_note(settings: Settings) -> list[str]:
    """Algorithm 2 is selected by its own frozen-protocol experiment (algorithm2_benchmark/); point to it."""
    root = PROJECT_ROOT / "algorithm2_benchmark" / "results"
    rows = []
    for d in sorted(root.glob("*/decision.json")) if settings.mode == "real" else []:
        cfg = json.loads((d.parent / "config.json").read_text())
        dec = json.loads(d.read_text())
        rows.append(f"`{d.parent.name}` ({cfg.get('level')}): default `{dec.get('default_scorer')}`, "
                    f"confirmed {dec.get('confirmed')}")
    if not rows:
        return []
    return ["> **Collection recommendations (algorithm 2)** are selected by the frozen-protocol experiment in "
            "`algorithm2_benchmark/` (see `algorithm2_benchmark/README.md` and each run's `final_report.md`): "
            + "; ".join(rows) + ". The `collection` section below is the earlier benchmark.", ""]


def export_summary(settings: Settings) -> str:
    runs = latest_runs(settings)
    lines = [f"# Evaluation results - {settings.mode} data", "",
             "Generated by `make export-evaluation` from the latest run of each experiment. Every number below comes "
             "from a run directory under `evaluation/runs/` (config, manifest, metrics, per-case rows, report).", ""]
    if settings.mode == "synthetic":
        lines += ["> **Synthetic mode.** These runs verify that the pipelines and algorithms work end to end on a "
                  "generated, fictional world. They say nothing about real recommendation quality.", ""]
    lines += _algorithm2_note(settings)
    for name in ORDER:
        r = runs.get(name)
        if r is None or r["manifest"] is None:
            lines += [f"## {name}", "", "not_run: no finished run recorded for this mode."
                      + (f" The attempt `{r['newer_unfinished']}` did not finish." if r else ""), ""]
            continue
        if r.get("newer_unfinished"):
            lines += [f"> Warning: a newer attempt `{r['newer_unfinished']}` did not finish; the last finished run "
                      "is shown.", ""]
        man = r["manifest"]
        rel = r["dir"].relative_to(PROJECT_ROOT) if r["dir"].is_relative_to(PROJECT_ROOT) else r["dir"]
        body = (r["dir"] / "report.md").read_text(encoding="utf-8")
        body = "\n".join(("#" + ln) if ln.startswith("#") else ln for ln in body.splitlines())
        lines += [body, "", f"_Run `{man['run_id']}` · status {man['status']} · dataset `{man['dataset_version']}` · "
                  f"{man['seconds']} s · commit {man.get('git_commit')}"
                  + (" + uncommitted changes" if man.get("git_dirty") else "") + f" · run dir `{rel}`_", ""]
    out = PROJECT_ROOT / "docs" / f"evaluation-results-{settings.mode}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return str(out)
